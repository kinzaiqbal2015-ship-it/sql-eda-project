/*
Project: Exploratory Data Analysis using SQL Server
Section 3: Magnitude analysis

Magnitude analysis compares business measures across categories
such as country, gender, and product category.
*/

-- 3.1 Total customers by country
SELECT
    country,
    COUNT(customer_key) AS total_customers
FROM gold.[gold.dim_customers]
GROUP BY country
ORDER BY total_customers DESC;

-- 3.2 Total customers by gender
SELECT
    gender,
    COUNT(customer_key) AS total_customers
FROM gold.[gold.dim_customers]
GROUP BY gender
ORDER BY total_customers DESC;

-- 3.3 Total products by category
SELECT
    category,
    COUNT(product_key) AS total_products
FROM gold.[gold.dim_products]
GROUP BY category
ORDER BY total_products DESC;

-- 3.4 Average product cost by category
SELECT
    category,
    AVG(cost) AS average_cost
FROM gold.[gold.dim_products]
GROUP BY category
ORDER BY average_cost DESC;

-- 3.5 Total revenue generated by each product category
SELECT
    p.category,
    SUM(f.sales_amount) AS total_revenue
FROM gold.[gold.fact_sales] AS f
LEFT JOIN gold.[gold.dim_products] AS p
    ON p.product_key = f.product_key
GROUP BY p.category
ORDER BY total_revenue DESC;

-- 3.6 Distribution of sold quantities across countries
SELECT
    c.country,
    SUM(f.quantity) AS total_quantity_sold
FROM gold.[gold.fact_sales] AS f
LEFT JOIN gold.[gold.dim_customers] AS c
    ON c.customer_key = f.customer_key
GROUP BY c.country
ORDER BY total_quantity_sold DESC;
